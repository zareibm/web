export function getPropertyBySlug(slug) {
  return PROPERTIES.find((property) => property.slug === slug)
}

export function getFeaturedProperties() {
  return PROPERTIES.filter((property) => property.featured)
}

/** Same type or same region, closest in price — always returns `count` items. */
export function getSimilarProperties(property, count = 3) {
  return PROPERTIES.filter((item) => item.id !== property.id)
    .sort((a, b) => {
      const score = (item) =>
        (item.type === property.type ? 0 : 1) +
        (item.location.region === property.location.region ? 0 : 1)
      return score(a) - score(b) || Math.abs(a.price - property.price) - Math.abs(b.price - property.price)
    })
    .slice(0, count)
}

